#!/usr/bin/env node
/**
 * Regenerates demo/src/app/shared/toasts-lib.generated.txt - the ambient type declarations
 * Monaco uses (via addExtraLib in code-editor.ts) to autocomplete the Playground's sandboxed
 * run() scope. Source of truth is the real, freshly-built ../../dist/index.d.ts - this is what
 * fixes https://github.com/Brentspine/brents-toasts/issues/64 ("Fix Monaco code suggestions"):
 * the old approach hand-copied a `TOASTS_DTS` string in code-editor.ts that silently drifted out
 * of sync with the actual public API every time src/ changed. Generating it here instead means
 * there is nothing left to remember to update.
 *
 * dist/index.d.ts (produced by rollup-plugin-dts) is a single file of global ambient
 * declarations (`declare const`, `declare class`, `interface`, `type`, ...) followed by one or
 * two trailing `export { ... }` / `export type { ... }` statements that just re-export those
 * already-declared names. Those trailing statements are the only thing that makes TypeScript
 * treat the file as a module (scoping every declaration to it) instead of a global script -
 * stripping them is enough to turn the rest back into plain global ambient declarations, which
 * is exactly the shape Monaco's addExtraLib needs for the Playground's sandbox (see
 * playground.ts's `run()`, which executes user code with these names as bare identifiers, not
 * imports).
 *
 * Run automatically via demo's `pre{start,build,test}` npm hooks - see demo/package.json. Like
 * the rest of the demo, this requires `npm run build` to have already been run at the repo root
 * (see the "Demo" section of CLAUDE.md); it fails loudly rather than silently falling back to a
 * stale copy if dist/index.d.ts is missing, since a stale fallback is exactly the bug this
 * script exists to prevent.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const distDtsPath = path.resolve(__dirname, '../../dist/index.d.ts');
const outPath = path.resolve(__dirname, '../src/app/shared/toasts-lib.generated.txt');

let source;
try {
  source = readFileSync(distDtsPath, 'utf8');
} catch {
  console.error(
    `[generate-monaco-lib] Could not read ${distDtsPath}.\n` +
      'Run `npm run build` at the repo root first (see the "Demo" section of CLAUDE.md), then retry.',
  );
  process.exit(1);
}

const stripped = source
  .split('\n')
  .filter((line) => !/^export\s/.test(line))
  .join('\n')
  .trim();

if (!stripped) {
  console.error(`[generate-monaco-lib] ${distDtsPath} produced no ambient declarations after stripping exports.`);
  process.exit(1);
}

const header =
  '// AUTO-GENERATED by demo/scripts/generate-monaco-lib.mjs from ../../dist/index.d.ts - do not edit by hand.\n' +
  '// Regenerated automatically by demo\'s pre{start,build,test} npm hooks; run `npm run generate:monaco-lib` to refresh manually.\n\n';

writeFileSync(outPath, header + stripped + '\n', 'utf8');
console.log(`[generate-monaco-lib] Wrote ${path.relative(process.cwd(), outPath)} from dist/index.d.ts.`);
